import assert from 'node:assert/strict';
import JSZip from 'jszip';
import { curateSourceWindows, memoryEvidenceContext, readMemoryExport, memoryFromRow } from './memoryCuration';
import { createFileOperationScope } from './fileOperationScope';
const scope = createFileOperationScope(() => ['family', 'adult']);
const chat = '[03/02/2020, 12:00] Alex: Today Jamie took a first step!';
assert.equal((await readMemoryExport(new File([chat], 'Maria.txt'), scope)), chat);
const zip = new JSZip(); zip.file('_chat.txt', chat); zip.file('photo.jpg', 'synthetic bytes');
const bytes = await zip.generateAsync({ type: 'uint8array' });
assert.equal(await readMemoryExport(new File([bytes], 'WhatsApp.zip'), scope), chat, 'reads only chat text, leaving media in the original export');
const ambiguous = new JSZip(); ambiguous.file('one/_chat.txt', 'one'); ambiguous.file('two/_chat.txt', 'two');
await assert.rejects(() => ambiguous.generateAsync({ type: 'uint8array' }).then(bytes => readMemoryExport(new File([bytes], 'multiple.zip'), scope)), /exactly one chat/);
await assert.rejects(() => readMemoryExport(new File(['x'], 'not-a-chat.pdf'), scope), /WhatsApp ZIP/);
const text = 'ordinary logistics\n'.repeat(2000) + '\n[01/01/2001] A birthday at the beach\nRemember the sandcastle?\n';
const windows = curateSourceWindows(text);
assert.equal(windows.partial, true); assert.ok(windows.text.length <= 19000); assert.match(windows.text, /birthday at the beach/);
assert.ok(text.includes(windows.text), 'selected windows retain exact original words');
assert.equal(curateSourceWindows('ordinary logistics\n'.repeat(2000)).text, '', 'no forced filler');
assert.equal(curateSourceWindows(chat).partial, false);
const evidenceContext = memoryEvidenceContext('x'.repeat(1000) + chat + 'y'.repeat(1000), chat);
assert.ok(evidenceContext.includes(chat)); assert.equal(evidenceContext.length, chat.length + 480, 'only a short provenance context is stored with each draft, not a full chat');
assert.equal(memoryFromRow({ date: '', title: 'A first step', sourceText: chat })?.date, '', 'unknown stays unknown');
assert.equal(memoryFromRow({ date: '', title: 'No evidence' }), null);
let current = 'one'; const cancelled = createFileOperationScope(() => [current]); current = 'two';
await assert.rejects(() => readMemoryExport(new File([chat], 'Maria.txt'), cancelled), /account, space/);
console.log('memoryCuration: bounded exact source windows, ZIP/TXT selection, no media auto-import, no filler and scope cancellation passed');
