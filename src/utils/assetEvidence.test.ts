import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import type { AssetItem, SlipItem } from '../types';
import { assetReceiptSource, linkAssetEvidence, missingAssetPurchaseDetails, receiptCurrencyConflict, unlinkAssetEvidence } from './assetEvidence';
import { fileContentUrl, FILE_BUCKET } from './fileReferences';

const asset: AssetItem = { id: 'asset', name: 'Desk', category: 'Furniture', createdAt: '2026-10-31' };
const slip: SlipItem = { id: 'slip', item: 'Desk', shop: 'Synthetic shop', purchaseDate: '2026-10-30', amount: '250', currency: 'EUR', returnByDate: '2026-11-15', warrantyUntil: '2028-10-30', createdAt: '2026-10-31' };
assert.deepEqual(missingAssetPurchaseDetails(asset, slip), { purchaseDate: '2026-10-30', purchaseLocation: 'Synthetic shop', purchasePrice: '250', currency: 'EUR' });
const recorded = { ...asset, purchaseDate: '2025-01-01', purchaseLocation: 'Original shop', purchasePrice: '0', currency: 'ZAR', purchaseReference: 'Original reference', warranties: [{ id: 'w', kind: 'retailer' as const }] };
assert.deepEqual(missingAssetPurchaseDetails(recorded, slip), {}, 'using details never overwrites existing values, zero prices or warranty records');
assert.deepEqual(missingAssetPurchaseDetails({ ...asset, currency: 'USD' }, slip), { purchaseDate: '2026-10-30', purchaseLocation: 'Synthetic shop' }, 'a EUR receipt cannot silently populate a USD price');
assert.equal(receiptCurrencyConflict({ ...asset, currency: 'USD' }, slip), true);
assert.equal(receiptCurrencyConflict({ ...asset, purchasePrice: '100', currency: 'USD' }, slip), false, 'existing price is left alone');
assert.equal(missingAssetPurchaseDetails({ ...asset, purchasePrice: '100' }, slip).currency, undefined, 'an existing amount is never relabelled');
assert.equal(missingAssetPurchaseDetails(asset, { ...slip, purchaseDate: '2026-02-31' }).purchaseDate, undefined);
assert.equal(missingAssetPurchaseDetails(asset, slip).returnByDate, undefined, 'a receipt link does not invent return policy or cover');
assert.deepEqual(asset, { id: 'asset', name: 'Desk', category: 'Furniture', createdAt: '2026-10-31' }, 'detail copying returns a patch and leaves the source untouched');
assert.deepEqual(linkAssetEvidence(['old', 'keep'], 'old'), ['old', 'keep']);
assert.deepEqual(linkAssetEvidence(['old'], 'new'), ['old', 'new']);
assert.deepEqual(unlinkAssetEvidence(['old', 'new'], 'old'), ['new']);

const path = 'families/space-a/slip-photos/receipt.jpg';
assert.equal(assetReceiptSource(fileContentUrl(path), 'space-a'), fileContentUrl(path));
assert.equal(assetReceiptSource(`https://firebasestorage.googleapis.com/v0/b/${FILE_BUCKET}/o/${encodeURIComponent(path)}?alt=media&token=retired`, 'space-a'), fileContentUrl(path));
assert.equal(assetReceiptSource(fileContentUrl(path), 'space-b'), null, 'another space cannot become this asset’s receipt');
assert.equal(assetReceiptSource('javascript:alert(1)', 'space-a'), null);
assert.equal(assetReceiptSource('https://external.invalid/pixel.jpg', 'space-a'), null);
assert.equal(assetReceiptSource('data:image/svg+xml;base64,PHN2Zz4=', 'space-a'), null);
assert.equal(assetReceiptSource('data:image/jpeg;base64,AAA=', 'space-a'), 'data:image/jpeg;base64,AAA=');

const component = readFileSync(new URL('../components/AssetEvidenceFields.tsx', import.meta.url), 'utf8');
assert.match(component, /scope, shared: true, dedupe: false/);
assert.match(component, /createFileOperationScope\(\(\) => \[auth\.currentUser\?\.uid, FAMILY_ID, latest\.current\.id, epoch\.current, editable\.current\]/);
assert.match(component, /epoch\.current\+\+/);
assert.match(component, /scope\.check\(\)/);
assert.match(component, /!!onChange && \(demo \|\| \(!loading && isAdmin\)\)/);
assert.match(component, /Use purchase details/);
assert.match(component, /patch\(missingAssetPurchaseDetails\(latest\.current, slip\)\)/);
assert.match(component, /patch\(\{ slipIds: linkAssetEvidence\(latest\.current\.slipIds, slip\.id\) \}\)/, 'linking a Slip changes only its reference');
assert.match(component, /ServiceDocChips/);
assert.doesNotMatch(component, /compressImage|readAsDataURL|deleteVaultFile|deleteSlipPhoto|deleteObject/);
assert.match(component, /notifyBusy\.current\?\.\(true\)/);
assert.match(component, /notifyBusy\.current\?\.\(false\)/);
assert.ok(component.includes("key={`${uid || 'guest'}:${familyId || 'none'}:${props.item.id}`}"), 'reader state remounts across accounts, spaces and assets');
assert.match(component, /getDocFromServer\(doc\(db, 'families', familyId!, 'reference', 'slips'\)\)/);
assert.match(component, /setSlipState\('unavailable'\)/);
assert.match(component, /Vault may be empty or unavailable/);
console.log('assetEvidence: explicit blank-only purchase copying, currency consistency, safe receipt sources and scoped original linking passed');
